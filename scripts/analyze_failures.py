#!/usr/bin/env python3
"""analyze_failures.py — dissect an auto_eval.jsonl log.

Groups brain failures by domain and by source (brain-hi vs qwen-* delegation),
surfaces patterns, and emits a feedback file of correct (question, answer)
pairs the brain should learn — generated by asking Qwen3 for the right answer.

Usage:
  python3 analyze_failures.py <eval.jsonl> [--teach feedback.txt]
"""
import argparse, itertools, json, sys, threading, urllib.request
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor

ENGINES = ["http://127.0.0.1:3000", "http://127.0.0.1:3002"]
_eng_lock = threading.Lock()
_eng_cycle = itertools.cycle(range(len(ENGINES)))
def next_engine():
    with _eng_lock:
        return ENGINES[next(_eng_cycle)]


def qwen(prompt, max_tokens=160, temp=0.2):
    chat = (f"<|im_start|>user\n{prompt}<|im_end|>\n"
            f"<|im_start|>assistant\n<think>\n\n</think>\n\n")
    body = json.dumps({"model": "qwen3-4b", "prompt": chat,
                       "max_tokens": max_tokens, "temperature": temp}).encode()
    req = urllib.request.Request(f"{next_engine()}/api/generate", data=body,
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=90) as r:
            return json.loads(r.read()).get("response", "").strip()
    except Exception as e:
        return f"<err {e}>"


# LaTeX / markup fragments — questions carrying these are bad training
# material for a byte-level PT-BR brain (real queries are plain prose).
_MARKUP = ("$", "\\times", "\\frac", "\\sqrt", "^{", "_{", "\\(", "\\[", "```")


def teach_pair(r):
    """Generate a validated (question, answer) pair from one failure.
    The teacher errs (Qwen3 is Q4-quantized) — so a second Qwen call
    cross-checks the answer. Returns (q, answer) or None if it fails
    validation (don't teach the brain something the teacher isn't sure of)."""
    q = r["q"]
    if any(tok in q for tok in _MARKUP):
        return None  # skip LaTeX/code questions — noise for a byte-level brain
    answer = qwen(f"Responda de forma direta, específica e factual "
                  f"(2-3 frases, em português, sem markup). Dê o dado concreto "
                  f"(nome, número, data) que a pergunta pede: {q}", temp=0.2)
    if not answer or answer.startswith("<err") or len(answer) < 20:
        return None
    if any(tok in answer for tok in _MARKUP):
        return None  # answer leaked markup — skip
    verdict = qwen(f"Pergunta: \"{q}\"\nResposta: \"{answer}\"\n"
                   f"Esta resposta é factualmente correta E dá o dado específico "
                   f"que a pergunta pede (não é evasiva)? "
                   f"Responda só SIM ou NAO.", max_tokens=8, temp=0.0).upper()
    if "SIM" not in verdict:
        return None  # teacher not confident — skip, never teach uncertain facts
    return (q, answer)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("log")
    ap.add_argument("--teach", default="", help="write correct pairs here for auto-learn")
    args = ap.parse_args()

    rows = []
    with open(args.log) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))

    if not rows:
        print("empty log")
        return

    by_domain = defaultdict(lambda: {"CERTO": 0, "PARCIAL": 0, "ERRADO": 0})
    by_source = defaultdict(lambda: {"CERTO": 0, "PARCIAL": 0, "ERRADO": 0})
    fails = []
    for r in rows:
        v = r["verdict"]
        by_domain[r["domain"]][v] += 1
        by_source[r.get("src", "?")][v] += 1
        if v != "CERTO":
            fails.append(r)

    print(f"═══ {args.log} — {len(rows)} questions, {len(fails)} non-CERTO ═══\n")

    print("BY DOMAIN (score = CERTO + 0.5·PARCIAL):")
    for d, c in sorted(by_domain.items(), key=lambda kv: -(kv[1]["CERTO"] + 0.5*kv[1]["PARCIAL"]) / max(sum(kv[1].values()),1)):
        tot = sum(c.values())
        sc = c["CERTO"] + 0.5 * c["PARCIAL"]
        print(f"  {sc:4.1f}/{tot:<3} ({100*sc/tot:3.0f}%)  {d}  ✓{c['CERTO']} ~{c['PARCIAL']} ✗{c['ERRADO']}")

    print("\nBY SOURCE (where the brain routed the answer):")
    for s, c in sorted(by_source.items()):
        tot = sum(c.values())
        sc = c["CERTO"] + 0.5 * c["PARCIAL"]
        print(f"  {sc:4.1f}/{tot:<3} ({100*sc/tot:3.0f}%)  {s}")

    print(f"\nFAILURES ({len(fails)}):")
    for r in fails[:40]:
        print(f"  [{r['verdict']}] [{r.get('src','?')}] {r['q'][:64]}")
        print(f"      brain: {r['answer'][:78]}")
        print(f"      judge: {r['reason'][:78]}")

    # Teach mode: for every failure, generate a VALIDATED correct answer
    # (Qwen3 answers, then cross-checks itself) — in parallel across engines.
    if args.teach and fails:
        print(f"\nTEACH — generating + validating answers for {len(fails)} failures...")
        with ThreadPoolExecutor(max_workers=len(ENGINES) * 2) as ex:
            pairs = list(ex.map(teach_pair, fails))
        kept = [p for p in pairs if p]
        with open(args.teach, "w") as tf:
            for q, ans in kept:
                tf.write(f"USER: {q}\n")
                tf.write(f"MODEL: {ans}\n\n")
        print(f"  validated {len(kept)}/{len(fails)} pairs → {args.teach}")
        print(f"  (rejected {len(fails)-len(kept)}: teacher not confident)")


if __name__ == "__main__":
    main()
